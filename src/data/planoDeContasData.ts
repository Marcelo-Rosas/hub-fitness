export function resolvePickerGroup(item: AccountItem): CoaPickerGroup {
  if (item.code === '1.1' || item.code.startsWith('1.1.')) return 'ativo_circulante';
  if (item.group === 'ATIVO') return 'ativo';
  if (item.code === '2.1' || item.code.startsWith('2.1.')) return 'passivo_circulante';
  if (item.group === 'PASSIVO') return 'passivo';
  if (item.group === 'RECEITAS') return 'receitas';
  if (item.group === 'CUSTOS E DESPESAS') return 'custos_despesas';
  return 'patrimonio';
}

