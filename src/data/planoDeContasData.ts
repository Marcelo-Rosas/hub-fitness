export interface AccountItem {
  code: string; // e.g. "1.1.01.01"
  name: string; // e.g. "Caixa Geral"
  level: 1 | 2 | 3 | 4; // Level of hierarchy (e.g., 1=Ativo, 2=Circulante, 3=Caixa e Equiv, 4=Caixa Geral)
  group: 'ATIVO' | 'PASSIVO' | 'PATRIMÔNIO LÍQUIDO' | 'RECEITAS' | 'CUSTOS E DESPESAS';
  nature: 'Devedora' | 'Credora';
  type: 'Sintética' | 'Analítica';
  isCriticalFatorR?: boolean; // True for Pró-labore Adicional & Folha
  isFatorRNumerator?: boolean; // Accounts included in Fator R numerator
  isFatorRExcluded?: boolean; // Accounts explicitly excluded (MO Terceirizada)
  isDasTax?: boolean; // DAS tax deduction account
  isCapex?: boolean; // CAPEX imobilizado (> R$ 1.200, > 1 ano)
  costCenterId?: string; // Default Cost Center
  notes?: string;
}

